/**
 * db/seed-insights.js
 *
 * Inserts one short sample post for the Insights (blog) section.
 *
 * Run:  npm run seed:insights
 *
 * Safe to run many times:
 *   - the post is inserted only when its slug does not exist yet
 *   - existing rows are never deleted or overwritten
 */

require("dotenv").config();

const pool    = require("../src/config/db");
const slugify = require("../src/utils/slugify");
const { validateBody } = require("../src/utils/postBlocks");

// ── The sample post ──────────────────────────────────────────────────
const samplePost = {
  title:     "Five signs your CCTV system needs attention",
  dek:       "A short monthly check catches most CCTV faults before they become security gaps.",
  category:  "Security",
  tags:      ["CCTV", "Maintenance", "Security"],
  coverWord: "Security",
  status:    "published",
  body: [
    {
      type: "p",
      text: "A CCTV system only protects a site while every camera, recorder and cable is doing its job. Most faults we find on site could have been caught early with a short monthly check.",
    },
    {
      type: "h2",
      text: "What to check every month",   // the h2 id is generated by validateBody
    },
    {
      type: "ul",
      items: [
        "Every camera gives a sharp, correctly exposed picture",
        "The recorder has at least two weeks of free storage",
        "Infrared illumination still works at night",
        "Cable terminations are dry and undamaged",
        "The recorder clock shows the correct time and date",
      ],
    },
    {
      type: "callout",
      title: "Need a maintenance contract?",
      text: "Our engineers run these checks for you and replace failing hardware under warranty. Contact us for a quotation.",
    },
  ],
};

// ── Main ──────────────────────────────────────────────────────────────
async function main() {
  try {
    const slug = slugify(samplePost.title);

    // Insert only when this slug does not exist yet
    const existing = await pool.query("SELECT id FROM posts WHERE slug = $1", [slug]);
    if (existing.rows.length > 0) {
      console.log(`ℹ️   Post "${samplePost.title}" already exists – skipped`);
      return;
    }

    // Validate + normalise the blocks with the same rules as the API
    // (this also generates the h2 id, so the seeded data matches what
    // the API would store)
    const result = validateBody(samplePost.body);
    if (!result.valid) {
      console.error(`❌  Seed body is invalid: ${result.message}`);
      process.exit(1);
    }

    // Today's date as YYYY-MM-DD (local time)
    const d  = new Date();
    const mm = String(d.getMonth() + 1).padStart(2, "0");
    const dd = String(d.getDate()).padStart(2, "0");
    const publishedAt = `${d.getFullYear()}-${mm}-${dd}`;

    await pool.query(
      `INSERT INTO posts
         (slug, title, dek, category, tags, cover_word, published_at, body, status)
       VALUES ($1, $2, $3, $4, $5::text[], $6, $7::date, $8::jsonb, $9)`,
      [
        slug,
        samplePost.title,
        samplePost.dek,
        samplePost.category,
        samplePost.tags,
        samplePost.coverWord,
        publishedAt,
        JSON.stringify(result.value),
        samplePost.status,
      ]
    );
    console.log(`✅  Post "${samplePost.title}" created`);

  } catch (err) {
    console.error("❌  Seed failed:", err.message);
  } finally {
    await pool.end();
    process.exit(0);
  }
}

main();
